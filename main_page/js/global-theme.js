// Theme Management Class
class ThemeManager {
    constructor() {
        this.currentTheme = this.getStoredTheme();
        this.init();
    }
    
    init() {
        // Apply theme on load
        this.applyTheme(this.currentTheme);
        
        // Listen for system theme changes if using system preference
        if (this.currentTheme === 'system') {
            window.matchMedia('(prefers-color-scheme: dark)').addEventListener('change', (e) => {
                if (this.currentTheme === 'system') {
                    this.applyTheme('system');
                }
            });
        }
    }
    
    getStoredTheme() {
        return localStorage.getItem('preferredTheme') || 'light';
    }
    
    applyTheme(theme) {
        let actualTheme = theme;
        
        if (theme === 'system') {
            actualTheme = window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
        }
        
        if (actualTheme === 'dark') {
            document.documentElement.setAttribute('data-theme', 'dark');
        } else {
            document.documentElement.removeAttribute('data-theme');
        }
        
        // Update theme toggle icon if it exists
        this.updateThemeToggleIcon(actualTheme);
    }
    
    updateThemeToggleIcon(theme) {
        const themeIcon = document.querySelector('.theme-toggle-icon i');
        const themeText = document.querySelector('.theme-toggle-text');
        
        if (themeIcon && themeText) {
            if (theme === 'dark') {
                themeIcon.className = 'bi bi-moon-stars-fill';
                const lang = localStorage.getItem('preferredLanguage') || 'en';
                themeText.textContent = globalTranslations[lang].darkMode;
            } else {
                themeIcon.className = 'bi bi-sun-fill';
                const lang = localStorage.getItem('preferredLanguage') || 'en';
                themeText.textContent = globalTranslations[lang].lightMode;
            }
        }
    }
    
    toggleTheme() {
        const currentActualTheme = document.documentElement.getAttribute('data-theme') === 'dark' ? 'dark' : 'light';
        const newTheme = currentActualTheme === 'dark' ? 'light' : 'dark';
        
        localStorage.setItem('preferredTheme', newTheme);
        this.currentTheme = newTheme;
        this.applyTheme(newTheme);
        
        return newTheme;
    }
    
    setTheme(theme) {
        localStorage.setItem('preferredTheme', theme);
        this.currentTheme = theme;
        this.applyTheme(theme);
    }
}

// Language Management Class
class LanguageManager {
    constructor() {
        this.currentLanguage = this.getStoredLanguage();
        this.init();
    }
    
    init() {
        this.applyLanguage(this.currentLanguage);
    }
    
    getStoredLanguage() {
        return localStorage.getItem('preferredLanguage') || 'en';
    }
    
    applyLanguage(lang) {
        const translations = globalTranslations[lang] || globalTranslations.en;
        
        // Update all elements with data-translate attribute
        document.querySelectorAll('[data-translate]').forEach(element => {
            const key = element.getAttribute('data-translate');
            if (translations[key]) {
                if (element.tagName === 'INPUT' && element.placeholder !== undefined) {
                    element.placeholder = translations[key];
                } else {
                    element.textContent = translations[key];
                }
            }
        });
        
        // Update document language attribute
        document.documentElement.lang = lang === 'tl' ? 'tl' : lang;
        
        // Dispatch custom event for language change
        window.dispatchEvent(new CustomEvent('languageChanged', { detail: { language: lang } }));
    }
    
    setLanguage(lang) {
        if (globalTranslations[lang]) {
            localStorage.setItem('preferredLanguage', lang);
            this.currentLanguage = lang;
            this.applyLanguage(lang);
            
            // Update theme toggle text if present
            const themeManager = window.themeManager;
            if (themeManager) {
                const currentTheme = document.documentElement.getAttribute('data-theme') === 'dark' ? 'dark' : 'light';
                themeManager.updateThemeToggleIcon(currentTheme);
            }
            
            return true;
        }
        return false;
    }
    
    getTranslation(key) {
        const translations = globalTranslations[this.currentLanguage] || globalTranslations.en;
        return translations[key] || key;
    }
}

// Initialize global managers
window.themeManager = new ThemeManager();
window.languageManager = new LanguageManager();

// Helper function to create theme toggle button
function createThemeToggleButton() {
    const currentTheme = document.documentElement.getAttribute('data-theme') === 'dark' ? 'dark' : 'light';
    const lang = localStorage.getItem('preferredLanguage') || 'en';
    const themeText = currentTheme === 'dark' ? globalTranslations[lang].darkMode : globalTranslations[lang].lightMode;
    const iconClass = currentTheme === 'dark' ? 'bi-moon-stars-fill' : 'bi-sun-fill';
    
    const button = document.createElement('button');
    button.className = 'theme-toggle';
    button.innerHTML = `
        <div class="theme-toggle-icon">
            <i class="bi ${iconClass}"></i>
        </div>
        <span class="theme-toggle-text">${themeText}</span>
    `;
    
    button.addEventListener('click', () => {
        window.themeManager.toggleTheme();
    });
    
    return button;
}

// Export for use in other scripts
window.globalTranslations = globalTranslations;
window.createThemeToggleButton = createThemeToggleButton;